"""Regenerates nurse/src/features/careforms/formDefs.ts from backend/app/modules/care_forms/forms.txt (the form source)."""
import json, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[1]
src = (root / "backend/app/modules/care_forms/forms.txt").read_text(encoding="utf-8").splitlines()
slug = lambda s: re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")[:40]
forms, cur = [], None
for line in src:
    if not line.strip():
        continue
    if line.startswith("@"):
        fid, title, purpose, who = line[1:].split("|", 3)
        cur = {"id": fid, "title": title, "purpose": purpose, "who": who, "items": []}
        forms.append(cur); continue
    k, _, rest = line.partition(":")
    if k in ("H", "N", "T"):
        cur["items"].append({"t": k, "text": rest})
    elif k == "W":
        cur["items"].append({"t": "W", "key": slug(rest), "label": rest})
    elif k == "F":
        cur["items"].append({"t": "F", "fields": [{"key": slug(x), "label": x} for x in rest.split("|")]})
    elif k == "C":
        label, opts = rest.split("|", 1)
        cur["items"].append({"t": "C", "key": slug(label), "label": label, "options": re.split(r"(?<! )/(?! )", opts)})
    elif k == "TBL":
        *cols, n = rest.split("|")
        cur["items"].append({"t": "TBL", "cols": cols, "rows": int(n)})
    elif k == "SIG":
        cur["items"].append({"t": "SIG", "roles": rest.split(",")})
    else:
        sys.exit(f"unknown line type: {line[:40]}")
out = root / "nurse/src/features/careforms/formDefs.ts"
out.write_text("// GENERATED by scripts/gen_careforms_defs.py from forms.txt. Do not edit by hand.\n"
               "export type FormItem =\n  | { t: 'H' | 'N' | 'T'; text: string }\n  | { t: 'W'; key: string; label: string }\n  | { t: 'F'; fields: { key: string; label: string }[] }\n"
               "  | { t: 'C'; key: string; label: string; options: string[] }\n  | { t: 'TBL'; cols: string[]; rows: number }\n  | { t: 'SIG'; roles: string[] };\n"
               "export type FormDef = { id: string; title: string; purpose: string; who: 'staff' | 'nurse' | 'client'; items: FormItem[] };\n"
               "export const FORM_DEFS: FormDef[] = " + json.dumps(forms, ensure_ascii=False, indent=1) + " as FormDef[];\n", encoding="utf-8")
print(len(forms), "forms ->", out)
